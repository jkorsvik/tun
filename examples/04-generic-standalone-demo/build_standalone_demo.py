#!/usr/bin/env python3
"""
build_standalone_demo.py — generates standalone_html_demo1.html

PROPOSAL artefact for docs/08-generic-artifact-model.md. Does not use
tools/build_dashboard.py and carries no dashboard vocabulary (no rows, no
dimension/measure/filter) on purpose: it exists to prove the generic
STANDALONE leg of the proposed layer-1 model on something that is not a
dashboard, without inventing a second real use case to justify it.

Still obeys principle 2 from issue #4 / docs/00-vision.md: HTML is never
hand-written, it is generated by a script from a template. A demo that
proves "generated, not hand-written" by being hand-written would be a
contradiction in the first line.

    python3 build_standalone_demo.py

No dependencies beyond the standard library — same rule as tools/.
"""
from __future__ import annotations

import datetime
import pathlib

OUT = pathlib.Path(__file__).parent / "standalone_html_demo1.html"
BUILT = datetime.datetime.now().strftime("%Y-%m-%d %H:%M %Z") or \
        datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

# Same the design system token values as templates/single-file-dashboard.html.
# Duplicated here deliberately, not imported: this proposal does not touch
# vedlikeholderen's template, and a generic layer-1 template (if this proposal is
# adopted) is where this would live permanently, shared by every specialisation.
TOKENS = """
  :root{
    --color-blue:#2F5D9E; --color-purple:#1B2A4A;
    --color-black-80:#333; --color-black-60:#666; --color-black-55:#737373; --color-black-8:#ebebeb;
    --color-black-3:#f8f8f8; --color-black-20:#ccc; --color-white:#fff;
    --ink:var(--color-black-80); --muted:var(--color-black-60);  /* 5.4:1 on --panel; Black 55% was 4.46:1 */
    --line:var(--color-black-8); --bg:var(--color-white); --panel:var(--color-black-3);
    --brand:var(--color-blue); --brand-dark:var(--color-purple);
    --sp-1:0.5rem; --sp-2:1rem; --sp-3:1.5rem; --sp-4:2rem;
  }
"""

SECTIONS = [
    ("seksjon-a", "Om denne filen",
     "Denne siden inneholder ingenting utenom det du ser nå — ingen data.js, "
     "ingen ekstern kilde, ingen kobling til noe som helst utenfor denne ene "
     "filen. Alt som trengs for at siden skal fungere fullt ut ligger inne i "
     "dette dokumentet, bakt inn ved byggetidspunkt."),
    ("seksjon-b", "Hvorfor tre seksjoner",
     "Navigasjonen over bytter mellom seksjoner med JavaScript "
     "(display:none / display:block) — samme HTML-fil, ikke tre separate "
     "sider. Det er prinsipp 4 fra issue #4: topplinje med meny er standard "
     "navigasjon, ikke en fast sidebar, og det gjelder uansett hva siden "
     "faktisk viser."),
    ("seksjon-c", "Hva denne filen ikke er",
     "Den er ikke et dashboard — ingen rader, ingen dimensjon, ingen måling, "
     "ingen filter. Den beviser kun den generiske STANDALONE-grenen i det "
     "foreslåtte lag-1-rammeverket (se docs/08-generic-artifact-model.md): "
     "at prinsippene om styling, proveniens og navigasjon holder helt "
     "uavhengig av om innholdet er tall, tekst eller noe annet."),
]

nav_buttons = "\n".join(
    f'      <button class="navbtn" data-target="{sid}">{title}</button>'
    for sid, title, _ in SECTIONS
)
sections_html = "\n".join(
    f'  <section id="{sid}" class="page" style="display:{"block" if i == 0 else "none"}">\n'
    f'    <h2>{title}</h2>\n    <p>{body}</p>\n  </section>'
    for i, (sid, title, body) in enumerate(SECTIONS)
)

HTML = f"""<!DOCTYPE html>
<html lang="nb">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Standalone HTML — prinsippdemo 1</title>
<!--
  ============================================================================
  Standalone HTML — prinsippdemo 1
  ----------------------------------------------------------------------------
  PROVENANCE
    Source data : none — this is a static demonstration, not a real report
    Built       : {BUILT}
    Requested by: en kollega
    Built by    : RAIWork, as a PROPOSAL artefact for
                  docs/08-generic-artifact-model.md (not yet adopted)
    Repo        : tun
    Generator   : examples/04-generic-standalone-demo/build_standalone_demo.py
  ----------------------------------------------------------------------------
  Tier 1, STANDALONE leg: fully self-contained, no server, no CDN, no sidecar
  file of any kind. Works offline and from a OneDrive-synced folder.
  This file intentionally carries NO dashboard vocabulary (no rows, no
  dimension/measure/filter) — see the file this generator's docstring points to
  for why.
  ============================================================================
-->
<style>
{TOKENS}
  *{{box-sizing:border-box}}
  body{{margin:0;background:var(--bg);color:var(--ink);
    font-family:"Eksempel AS",-apple-system,BlinkMacSystemFont,"Segoe UI",system-ui,sans-serif;
    font-size:1rem;line-height:1.5}}
  header{{background:var(--brand-dark);color:var(--color-white);padding:var(--sp-3) var(--sp-4)}}
  header h1{{margin:0;font-size:1.5rem;line-height:2rem;font-weight:500}}
  header .meta{{opacity:.85;font-size:.875rem;line-height:1.5rem;margin-top:var(--sp-1)}}
  nav{{display:flex;gap:var(--sp-2);background:var(--panel);padding:var(--sp-2) var(--sp-4);
    border-bottom:1px solid var(--line)}}
  .navbtn{{min-height:2.75rem;padding:.5rem .9rem;border:1px solid var(--color-black-20);border-radius:.25rem;
    background:var(--color-white);font-family:inherit;font-size:.875rem;cursor:pointer;
    color:var(--ink)}}
  .navbtn:hover{{border-color:var(--brand);color:var(--brand)}}
  .navbtn.active{{background:var(--brand);color:var(--color-white);border-color:var(--brand)}}
  main{{padding:var(--sp-3) var(--sp-4);max-width:52rem;margin:0 auto}}
  .page h2{{font-weight:500}}
  .page p{{color:var(--ink)}}
  @media print{{nav{{display:none}}}}
</style>
</head>
<body>
<header>
  <h1>Standalone HTML — prinsippdemo 1</h1>
  <div class="meta">Ingen data.js · ingen ekstern kilde · én fil</div>
</header>
<nav>
{nav_buttons}
</nav>
<main>
{sections_html}
</main>
<script>
  document.querySelectorAll('.navbtn').forEach(function(btn, i) {{
    if (i === 0) btn.classList.add('active');
    btn.addEventListener('click', function() {{
      document.querySelectorAll('.page').forEach(p => p.style.display = 'none');
      document.querySelectorAll('.navbtn').forEach(b => b.classList.remove('active'));
      document.getElementById(btn.dataset.target).style.display = 'block';
      btn.classList.add('active');
    }});
  }});
</script>
</body>
</html>
"""

OUT.write_text(HTML, encoding="utf-8")
print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
print("next: python3 tools/verify_standalone_core.py " + str(OUT))
