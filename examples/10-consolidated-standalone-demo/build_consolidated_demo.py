def placeholder_mark_svg(height_px: int = 26, color: str = FG) -> str:
    # Explicit width, not left to intrinsic/aspect-ratio inference: the mobile
    # test round (2026-09-07, OneDrive share link) found the logo invisible in
    # the boxed comparison — this file only ever set `height`, relying on the
    # browser to derive width from the viewBox aspect ratio. That inference is
    # NOT reliably supported across mobile WebViews (measured gap, not a
    # theoretical one — the icon SVGs elsewhere in this file already set both
    # dimensions and were not reported missing). Fix: always emit both.
    width_px = round(height_px * 116 / 80, 1)
    return (
        f'<svg width="{width_px}" height="{height_px}" viewBox="0 0 116 80" fill="{color}" '
        f'xmlns="http://www.w3.org/2000/svg" role="img" aria-label="Eksempel AS">{MARK_PATHS}</svg>'
    )


