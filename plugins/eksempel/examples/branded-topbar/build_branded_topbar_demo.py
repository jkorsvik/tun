MARK_PATHS = """
      <path d="M8 8h56v14H22v11h36v14H22v11h42v14H8z" /><circle cx="96" cy="65" r="9" />
"""

def logo_svg(height_px: int = 28, color: str = FG) -> str:
    return (
        f'<svg height="{height_px}" viewBox="0 0 116 80" fill="{color}" '
        f'xmlns="http://www.w3.org/2000/svg" role="img" aria-label="Eksempel AS">{MARK_PATHS}</svg>'
    )

