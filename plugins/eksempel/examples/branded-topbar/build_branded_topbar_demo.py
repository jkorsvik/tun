def icon_svg(icon: tuple, size: int = 24, color: str = FG) -> str:
    viewbox, path_template = icon
    return (
        f'<svg width="{size}" height="{size}" viewBox="{viewbox}" fill="none" '
        f'xmlns="http://www.w3.org/2000/svg" aria-hidden="true">'
        f'{path_template.format(c=color)}</svg>'
    )

